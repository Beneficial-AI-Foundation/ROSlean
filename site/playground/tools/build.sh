#!/bin/sh
# Builds site/playground/roslean_core.{js,wasm} from core/: the Lean core of
# the two nodes, compiled for the browser. See ../README.md.
#
# Needs on PATH: lake and lean (elan), emcc and em++ (an activated Emscripten
# SDK), git. Environment:
#   WORK       a scratch directory outside the repository (required)
#   LEAN4_SRC  a checkout of github.com/leanprover/lean4 at the commit of the
#              pinned toolchain (default: cloned into $WORK/lean4-src)
#   LIBUV_SRC  a checkout of github.com/libuv/libuv at the tag Lean's build
#              names (default: cloned into $WORK/libuv)
#   JOBS       parallel compilations (default 8)
#
# What goes into the .wasm, and from where:
#   1. the C that `lake build` generates for ROSleanCore (the same files the
#      ROS package compiles, ros/roslean_core/CMakeLists.txt);
#   2. ros/roslean_core/src/runtime.c, the same helper file as in the ROS
#      package;
#   3. Lean's standard library `Init` as C, generated here from the sources
#      the toolchain ships (<toolchain>/src/lean/Init) with the toolchain's
#      own `lean -c`. Lean's releases have no WebAssembly build of it for
#      this version;
#   4. Lean's runtime (src/runtime/*.cpp of LEAN4_SRC), compiled without
#      threads, without GMP (Lean's own big-number code, mpz.cpp and mpn.cpp,
#      is used) and without mimalloc (the C library's malloc is used);
#   5. one file of libuv (src/uv-common.c, for uv_strerror) and the stand-ins
#      in wasm_shim/.
set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../.." && pwd)
OUT="$HERE/.."
. "$HERE/hashes.sh"

: "${WORK:?set WORK to a scratch directory outside the repository}"
JOBS=${JOBS:-8}
LIBUV_TAG=v1.53.0   # src/CMakeLists.txt of Lean 4.37.0-rc1, "GIT_TAG"
mkdir -p "$WORK"
WORK=$(cd "$WORK" && pwd)
case "$WORK/" in "$ROOT"/*) echo "WORK must be outside the repository" >&2; exit 1 ;; esac
for tool in lake lean emcc em++ git; do
  command -v "$tool" >/dev/null 2>&1 || { echo "$tool not found on PATH" >&2; exit 1; }
done

# --- 1. the core, as C --------------------------------------------------
echo "== lake build ROSleanCore"
(cd "$ROOT/core" && lake build ROSleanCore)
SYSROOT=$(cd "$ROOT/core" && lean --print-prefix)
LEAN_VERSION=$(cd "$ROOT/core" && lean --version)
LEAN_GITHASH=$(cd "$ROOT/core" && lean --githash)
IR="$ROOT/core/.lake/build/ir"

# --- sources of the runtime ---------------------------------------------
LEAN4_SRC=${LEAN4_SRC:-$WORK/lean4-src}
if [ ! -d "$LEAN4_SRC/src/runtime" ]; then
  echo "== cloning lean4 at $LEAN_GITHASH into $LEAN4_SRC"
  git init -q "$LEAN4_SRC"
  git -C "$LEAN4_SRC" fetch -q --depth 1 https://github.com/leanprover/lean4.git "$LEAN_GITHASH"
  git -C "$LEAN4_SRC" checkout -q FETCH_HEAD
fi
have=$(git -C "$LEAN4_SRC" rev-parse HEAD)
[ "$have" = "$LEAN_GITHASH" ] || {
  echo "LEAN4_SRC is at $have, the toolchain was built from $LEAN_GITHASH" >&2; exit 1; }
cmp -s "$SYSROOT/include/lean/lean.h" "$LEAN4_SRC/src/include/lean/lean.h" || {
  echo "lean.h of the toolchain and of LEAN4_SRC differ" >&2; exit 1; }
LIBUV_SRC=${LIBUV_SRC:-$WORK/libuv}
if [ ! -f "$LIBUV_SRC/src/uv-common.c" ]; then
  echo "== cloning libuv $LIBUV_TAG into $LIBUV_SRC"
  git clone -q --depth 1 --branch "$LIBUV_TAG" https://github.com/libuv/libuv.git "$LIBUV_SRC"
fi
LIBUV_COMMIT=$(git -C "$LIBUV_SRC" rev-parse HEAD)

B=$(mktemp -d "$WORK/build.XXXXXX")
echo "== building in $B"

# Headers: lean.h as shipped; config.h without LEAN_MIMALLOC (lean.h then
# allocates through the runtime's lean_alloc_object, which calls malloc);
# version.h with the target replaced.
mkdir -p "$B/inc/lean"
cp "$SYSROOT/include/lean/lean.h" "$SYSROOT/include/lean/lean_gmp.h" \
   "$SYSROOT/include/lean/lean_libuv.h" "$B/inc/lean/"
printf '#pragma once\n#include <lean/version.h>\n\n#define LEAN_IS_STAGE0 0\n' > "$B/inc/lean/config.h"
sed 's/^#define LEAN_PLATFORM_TARGET .*/#define LEAN_PLATFORM_TARGET "wasm32-unknown-emscripten"/' \
  "$SYSROOT/include/lean/version.h" > "$B/inc/lean/version.h"
printf '#define LEAN_GITHASH "%s"\n' "$LEAN_GITHASH" > "$B/inc/githash.h"

# --- 3. Init as C ---------------------------------------------------------
echo "== generating C for Init from $SYSROOT/src/lean"
(cd "$SYSROOT/src/lean" && find Init Init.lean -name '*.lean' | sed 's/\.lean$//' |
  xargs -P "$JOBS" -n 1 "$HERE/regen1.sh" "$SYSROOT" "$B/init_c")
# Lean's repository carries the same files, generated by its own build
# (stage0/stdlib). They are not used here, only compared, as a check that
# the options above are the ones Lean's build uses.
n_init=0; n_same=0
for f in $(cd "$B/init_c" && find . -name '*.c'); do
  n_init=$((n_init + 1))
  if cmp -s "$B/init_c/$f" "$LEAN4_SRC/stage0/stdlib/$f"; then n_same=$((n_same + 1)); fi
done
echo "   $n_init files, $n_same identical to stage0/stdlib of LEAN4_SRC"

# --- compile --------------------------------------------------------------
# -ffp-contract=off and -O3 -DNDEBUG are Lean's own flags for generated code
# (`leanc --print-cflags`) and for its runtime.
COMMON="-O3 -DNDEBUG -ffp-contract=off -fwasm-exceptions -w"
echo "== compiling Init and the core"
export CC1=emcc FLAGS="$COMMON -I$B/inc"
(cd "$B/init_c" && find . -name '*.c' | sed 's|^\./||' |
  awk -v o="$B/obj/init" '{ c = $0; sub(/\.c$/, ".o"); print c, o "/" $0 }' |
  xargs -P "$JOBS" -n 2 "$HERE/cc1.sh")
(cd "$IR" && find . -name '*.c' | sed 's|^\./||' |
  awk -v o="$B/obj/core" '{ c = $0; sub(/\.c$/, ".o"); print c, o "/" $0 }' |
  xargs -P "$JOBS" -n 2 "$HERE/cc1.sh")
emcc $COMMON -I"$B/inc" -I"$ROOT/ros/roslean_core/include" \
  -c "$ROOT/ros/roslean_core/src/runtime.c" -o "$B/obj/core/runtime_c.o"

echo "== compiling Lean's runtime"
# The list is RUNTIME_OBJS of src/runtime/CMakeLists.txt. LEAN_MULTI_THREAD,
# LEAN_USE_GMP and LEAN_MIMALLOC are not defined. `-include mutex`: in the
# build without threads, runtime/thread.h names std::adopt_lock_t without
# including its header.
RT="debug thread mpz utf8 object apply exception interrupt memory stackinfo compact
  init_module io hash byteslice platform alloc allocprof sharecommon stack_overflow process
  object_ref mpn mutex libuv uv/net_addr uv/event_loop uv/timer uv/tcp uv/udp uv/dns uv/system
  uv/signal uv/process openssl cadical"
export CC1=em++ FLAGS="$COMMON -std=c++20 -DLEAN_EMSCRIPTEN -include mutex -I$B/inc -I$LEAN4_SRC/src -I$LIBUV_SRC/include -I$HERE/wasm_shim"
(cd "$LEAN4_SRC/src/runtime" && for f in $RT; do echo "$f.cpp $B/obj/rt/$f.o"; done |
  xargs -P "$JOBS" -n 2 "$HERE/cc1.sh")
emcc -O3 -DNDEBUG -w -I"$LIBUV_SRC/include" -I"$LIBUV_SRC/src" \
  -c "$LIBUV_SRC/src/uv-common.c" -o "$B/obj/rt/uv-common.o"
emcc -O3 -c "$HERE/wasm_shim/uv_stubs.c" -o "$B/obj/rt/uv_stubs.o"

# --- link -----------------------------------------------------------------
# Exported: every function of ffi.h, and malloc/free for the byte arrays the
# JavaScript shim hands over. The linker reports an undefined symbol only if
# live code refers to it, so this fails if the core starts to need a part of
# libuv or of the system that is not linked.
EXPORTS=$(grep -o 'roslean_[a-z0-9_]*(' "$ROOT/ros/roslean_core/include/roslean_core/ffi.h" |
  tr -d '(' | LC_ALL=C sort -u | sed 's/^/_/' | tr '\n' ',')
echo "== linking"
# shellcheck disable=SC2046
em++ -O3 -fwasm-exceptions $(find "$B/obj" -name '*.o' | LC_ALL=C sort) -o "$B/roslean_core.js" \
  -sMODULARIZE=1 -sEXPORT_ES6=1 -sEXPORT_NAME=createRosleanCore -sENVIRONMENT=web,node \
  -sALLOW_MEMORY_GROWTH=1 -sSTACK_SIZE=8MB \
  -sEXPORTED_FUNCTIONS="${EXPORTS}_malloc,_free" -sEXPORTED_RUNTIME_METHODS=HEAPU8

cp "$B/roslean_core.js" "$B/roslean_core.wasm" "$OUT/"
chmod 644 "$OUT/roslean_core.js" "$OUT/roslean_core.wasm"

# --- manifest ---------------------------------------------------------------
{
  echo "# Written by tools/build.sh. tools/check_fresh.sh compares these with the tree."
  echo "lean_version=$LEAN_VERSION"
  echo "lean_commit=$LEAN_GITHASH"
  echo "emscripten=$(emcc --version | head -1)"
  echo "libuv=$LIBUV_TAG $LIBUV_COMMIT"
  echo "init_modules=$n_init"
  echo "init_identical_to_stage0=$n_same"
  echo "lean_sources_sha256=$(hash_lean_sources)"
  echo "generated_c_sha256=$(hash_generated_c)"
  echo "glue_sha256=$(hash_glue)"
  echo "wasm_sha256=$(sha "$OUT/roslean_core.wasm" | cut -d' ' -f1)"
  echo "js_sha256=$(sha "$OUT/roslean_core.js" | cut -d' ' -f1)"
  echo "wasm_bytes=$(wc -c < "$OUT/roslean_core.wasm" | tr -d ' ')"
  echo "wasm_gzip_bytes=$(gzip -9 -c "$OUT/roslean_core.wasm" | wc -c | tr -d ' ')"
} > "$OUT/roslean_core.manifest"
cat "$OUT/roslean_core.manifest"
echo "== done. The build directory $B can be deleted."
