#!/bin/sh
# Fails if the committed roslean_core.{js,wasm} do not belong to this tree.
#
# Always checked (needs only a shell and sha256): the Lean sources of core/,
# the glue (runtime.c, ffi.h, the build scripts) and the two artefacts
# against the hashes in roslean_core.manifest.
# With --lake (needs the Lean toolchain): also builds core/ and compares the
# generated C, which is what was actually compiled.
#
# It cannot tell whether the .wasm was produced by build.sh from those
# inputs; for that, run build.sh and see whether the files change.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../.." && pwd)
. "$HERE/hashes.sh"

bad=0
check() {  # name, recorded, actual
  if [ "$2" = "$3" ]; then echo "ok     $1"; else echo "STALE  $1: manifest $2, tree $3"; bad=1; fi
}
check "Lean sources of core/" "$(manifest_get lean_sources_sha256)" "$(hash_lean_sources)"
check "glue and build scripts" "$(manifest_get glue_sha256)" "$(hash_glue)"
check "roslean_core.wasm" "$(manifest_get wasm_sha256)" \
  "$(sha "$ROOT/site/playground/roslean_core.wasm" | cut -d' ' -f1)"
check "roslean_core.js" "$(manifest_get js_sha256)" \
  "$(sha "$ROOT/site/playground/roslean_core.js" | cut -d' ' -f1)"
if [ "${1:-}" = "--lake" ]; then
  (cd "$ROOT/core" && lake build ROSleanCore >/dev/null)
  check "C generated by Lean" "$(manifest_get generated_c_sha256)" "$(hash_generated_c)"
fi
if [ "$bad" -ne 0 ]; then
  echo "Rebuild with site/playground/tools/build.sh (see site/playground/README.md)." >&2
  exit 1
fi
